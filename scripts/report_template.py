"""Renders reports/01_dataset_report.md from the dict produced by eda.py.

Kept as a separate module so eda.py's task functions stay the focus of a
diff, and so the report text can be adjusted without touching the pipeline.
"""
from __future__ import annotations


def _stats_line(stats: dict) -> str:
    if not stats:
        return "n/a"
    keys = ["count", "mean", "std", "min", "25%", "50%", "75%", "max"]
    parts = []
    for k in keys:
        if k in stats:
            v = stats[k]
            parts.append(f"{k}={v:.3g}" if isinstance(v, float) else f"{k}={v}")
    return ", ".join(parts)


def _top(d: dict, n: int = 10) -> str:
    items = sorted(d.items(), key=lambda kv: -kv[1] if isinstance(kv[1], (int, float)) else 0)[:n]
    return ", ".join(f"{k}: {v}" for k, v in items)


